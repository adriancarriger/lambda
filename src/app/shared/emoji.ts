/** The emoji to draw for an icon, or null for the plain cube. */
export const iconEmoji = (icon: string | null | undefined): string | null => {
  if (icon === null || icon === undefined || icon.trim() === '') {
    return null;
  }

  const code = /^:([a-z0-9_+-]+):$/i.exec(icon.trim())?.[1];

  if (code !== undefined) {
    return SHORTCODES[code.toLowerCase()] ?? null;
  }

  // Already a character (an emoji someone typed), not an icon's name.
  return /^[A-Za-z0-9 ]+$/.test(icon) ? null : icon;
};
